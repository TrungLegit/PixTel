export function getWeaponSkillId(defId?: string): WeaponSkillId | null {
  if (!defId) return null;
  const def = ITEMS[defId];
  if (def?.weaponSkillId) return def.weaponSkillId;
  return WEAPON_TO_SKILL_MAP[defId] ?? null;
}

export function getWeaponSkillForItem(defId?: string): WeaponSkillDef | null {
  const id = getWeaponSkillId(defId);
  return id ? WEAPON_SKILLS[id] : null;
}
